// Program: Print numbers from 0 to 10 using a while loop.
// Output Example:
// 0
// 1
// 2
// ...
// 10
//
// Concept: Loops (while loop)

public class WhileLoop {

    public static void main(String[] args) {

        int i = 0;

        while (i <= 10) {
            System.out.println(i);
            i++; // update i
        }
    }
}